export function getGoogleMapsSearchUrl(building: UoPBuilding): string {
  const query = encodeURIComponent(`${building.name}, ${building.address}, ${building.postcode}`);
  return `https://www.google.com/maps/search/?api=1&query=${query}`;
}

export function getGoogleMapsDirUrl(building: UoPBuilding): string {
  const dest = encodeURIComponent(`${building.lat},${building.lng}`);
  return `https://www.google.com/maps/dir/?api=1&destination=${dest}&travelmode=walking`;
}
